"""File storage behind one interface. Local disk in dev; S3-compatible (Cloudflare R2) in prod.

Keys are generated by us (random ids), never taken from user input.
"""

from __future__ import annotations

import re
import shutil
from pathlib import Path
from typing import Protocol

_KEY = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._/-]{0,299}$")


def check_key(key: str) -> str:
    if not _KEY.match(key) or ".." in key or "//" in key:
        raise ValueError(f"invalid storage key: {key!r}")
    return key


class Storage(Protocol):
    def path(self, key: str) -> Path: ...
    def put_file(self, key: str, src: Path) -> None: ...
    def exists(self, key: str) -> bool: ...
    def delete(self, key: str) -> None: ...


class LocalStorage:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def path(self, key: str) -> Path:
        full = (self.root / check_key(key)).resolve()
        if self.root not in full.parents and full != self.root:
            raise ValueError("storage key escapes the storage root")
        return full

    def put_file(self, key: str, src: Path) -> None:
        dst = self.path(key)
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)

    def exists(self, key: str) -> bool:
        return self.path(key).exists()

    def delete(self, key: str) -> None:
        target = self.path(key)
        if target.is_dir():
            shutil.rmtree(target, ignore_errors=True)
        elif target.exists():
            target.unlink()
